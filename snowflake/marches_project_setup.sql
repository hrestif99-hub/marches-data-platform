-- Setup initial du projet Marchés dans Snowflake
USE ROLE ACCOUNTADMIN;

-- Warehouse minuscule qui s'éteint après 60 s d'inactivité (économise les crédits)
CREATE WAREHOUSE IF NOT EXISTS MARCHES_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- Base et couches
CREATE DATABASE IF NOT EXISTS MARCHES;
CREATE SCHEMA IF NOT EXISTS MARCHES.RAW;
CREATE SCHEMA IF NOT EXISTS MARCHES.STAGING;
CREATE SCHEMA IF NOT EXISTS MARCHES.MARTS;

-- Rôle dédié au projet (on n'utilise pas ACCOUNTADMIN au quotidien)
CREATE ROLE IF NOT EXISTS MARCHES_ROLE;
GRANT USAGE ON WAREHOUSE MARCHES_WH TO ROLE MARCHES_ROLE;
GRANT ALL ON DATABASE MARCHES TO ROLE MARCHES_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE MARCHES TO ROLE MARCHES_ROLE;
GRANT ROLE MARCHES_ROLE TO USER "hrestif99";

-- Vérification
USE ROLE MARCHES_ROLE;
SHOW SCHEMAS IN DATABASE MARCHES;

SELECT CURRENT_REGION();

-- Fuseau horaire du compte en UTC (convention du projet : toutes les dates en UTC).
-- ALTER ACCOUNT exige ACCOUNTADMIN : lancée avec MARCHES_ROLE (rôle actif juste au-dessus),
-- la commande avait échoué faute de privilèges. D'où le USE ROLE ACCOUNTADMIN juste avant.
USE ROLE ACCOUNTADMIN;
ALTER ACCOUNT SET TIMEZONE = 'UTC';
